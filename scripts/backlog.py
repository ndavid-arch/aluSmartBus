def story(as_a, i_want, so_that, criteria, frs, notes=""):
    """Build the markdown body of a user story issue."""
    body = f"## User story\nAs a **{as_a}**, I want {i_want} so that {so_that}.\n\n"
    body += "## Acceptance criteria\n" + "\n".join(f"- [ ] {c}" for c in criteria) + "\n\n"
    body += f"## Requirements\n{frs}\n"
    if notes:
        body += f"\n## Notes\n{notes}\n"
    return body


def task(what, done, notes=""):
    """Build the markdown body of a task or spike issue."""
    body = f"## What needs doing\n{what}\n\n## Done when\n" + "\n".join(f"- [ ] {d}" for d in done) + "\n"
    if notes:
        body += f"\n## Notes\n{notes}\n"
    return body


